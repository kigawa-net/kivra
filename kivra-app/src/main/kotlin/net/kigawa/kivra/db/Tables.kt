object DevelopmentRunsTable : Table("development_runs") {
    val runId = char("run_id", 26)
    val taskId = varchar("task_id", 128)
    val taskUpdatedAt = datetime("task_updated_at").nullable()
    val state = varchar("state", 32)
    val currentStage = varchar("current_stage", 32).nullable()
    val stateReason = varchar("state_reason", 64).nullable()
    val attempt = integer("attempt").default(0)
    val planRevision = integer("plan_revision").default(0)
    val leaseOwner = varchar("lease_owner", 64).nullable()
    val leaseGeneration = long("lease_generation").default(0)
    val leaseExpiresAt = datetime("lease_expires_at").nullable()
    val holdReason = varchar("hold_reason", 64).nullable()
    val cancelRequested = bool("cancel_requested").default(false)
    val nextRetryAt = datetime("next_retry_at").nullable()
    val budgetJson = text("budget_json").nullable()
    val traceId = varchar("trace_id", 64).nullable()
    val completionMode = varchar("completion_mode", 16)
    val prRepository = varchar("pr_repository", 255).nullable()
    val prHeadSha = varchar("pr_head_sha", 64).nullable()
    val prNumber = long("pr_number").nullable()
    val prNodeId = varchar("pr_node_id", 255).nullable()
    val prRepositoryId = long("pr_repository_id").nullable()
    val prBaseRef = varchar("pr_base_ref", 255).nullable()
    val prPolicyRevision = varchar("pr_policy_revision", 255).nullable()
    val prReviewManifestDigest = varchar("pr_review_manifest_digest", 255).nullable()
    val completionMergeSha = varchar("completion_merge_sha", 64).nullable()
    // V9: API-submitted Tasks (Issue #112). Null for runs created by the workflow path.
    val taskTitle = varchar("task_title", 200).nullable()
    // V17: the task body (manual, plus the resolved reference after a separator) and the reference it came from (owner/repo#n).
    val taskBody = text("task_body").nullable()
    val taskSource = varchar("task_source", 255).nullable()
    val principal = varchar("principal", 256).nullable()
    val idempotencyKey = varchar("idempotency_key", 128).nullable()
    val completionEvidenceRef = varchar("completion_evidence_ref", 255).nullable()
    val completionObservedAt = datetime("completion_observed_at").nullable()
    val version = long("version").default(0)
    val createdAt = datetime("created_at")
    val updatedAt = datetime("updated_at")

    // active_flag is a generated column and is intentionally not mapped.
    override val primaryKey = PrimaryKey(runId)
}

