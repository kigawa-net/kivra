package net.kigawa.kivra.core.chat

import net.kigawa.kivra.core.autopilot.PLAN_BLOCK_REASONS

/*
 * The project chat's action proposals (ADR 0023, stage 1: rule-based, no LLM). The AI never executes anything: a proposal is a row that
 * an operator confirms or dismisses. The server holds the allow-list of codes ([ChatActionCode]) and generates each label itself; no
 * proposal text comes from a model or from the operator's free text.
 *
 * The rules here are pure. The repository reads the facts (the root orders and the cycle's Tasks) and calls [proposeChatActions] and
 * [isCycleStuck]. A proposal is only a suggestion: the confirmation checks everything again under the repository's own locks.
 */

/**
 * The allow-list of actions the chat may propose. Each code names one REST operation the confirmation runs. A new code is added here and
 * in the repository's dispatch. Stage 3 (LLM-written proposals) and stage 4 (the UNPRICED budget acknowledgement) are not in this list yet.
 */
enum class ChatActionCode(
    /** The fixed Japanese label shown to the operator. Generated by the server; never taken from a request or from text. */
    val label: String,
    /** What the proposal's target ID names: an order (its version) or a Task (its version). Decides which row the version is read from. */
    val targetKind: ChatTargetKind,
) {
    ORDER_START_CYCLE("周を開始する", ChatTargetKind.ORDER),
    ORDER_ABANDON_CYCLE("進行中の周を放棄する", ChatTargetKind.ORDER),

    /** The same operation as `POST /api/selfdev/orders/{id}/stop-request` (permission STOP_REQUEST), as the operator. Always a proposal. */
    ORDER_STOP_REQUEST("order の停止を要求する", ChatTargetKind.ORDER),

    /** The same operation as the goal page's replan button (`POST /api/selfdev/goals/{id}/replan`), on the cycle's root Task. */
    TASK_REPLAN("計画に失敗した周を再計画する", ChatTargetKind.TASK),

    /** The goal page's approval (`POST /api/selfdev/tasks/{id}/approve`) of a child Task that waits for approval (ADR 0023 stage 2). */
    TASK_APPROVE("承認待ちの Task を承認する", ChatTargetKind.TASK),

    /** The goal page's rejection (`POST /api/selfdev/tasks/{id}/reject`: the Task is skipped) of a child Task that waits (ADR 0023 stage 2). */
    TASK_REJECT("承認待ちの Task を見送る", ChatTargetKind.TASK),

    /**
     * The members route's add (`PUT /api/projects/{id}/members/{assigneeId}`), as the operator (ADR 0023 追補 5). Only the chat's AI proposes it;
     * the rules never do. The target is the assignee; the expected value is the membership ([MEMBER_ABSENT]); the role is the row's parameter.
     */
    MEMBER_ADD("メンバーを追加する", ChatTargetKind.ASSIGNEE),

    /**
     * The members route's removal (`DELETE /api/projects/{id}/members/{assigneeId}`), as the operator (ADR 0023 追補 5). A removal, not a
     * deactivation: the repository has no deactivation. Only the chat's AI proposes it. The expected value is [MEMBER_PRESENT].
     */
    MEMBER_REMOVE("メンバーを削除する", ChatTargetKind.ASSIGNEE),
}

/**
 * The kind of row a proposal's target ID names (V56 keeps one target column for all codes; V57 stores the kind too). An ASSIGNEE target has no
 * version: its expected value is the membership ([MEMBER_PRESENT] or [MEMBER_ABSENT]) when the proposal was made.
 */
enum class ChatTargetKind { ORDER, TASK, ASSIGNEE }

/** Who made a proposal (V57 `origin`): the rule-based proposer, or the chat's AI through a tool call. Never free text. */
enum class ChatActionOrigin { RULE, AI }

/** The expected value of a member proposal: the assignee is a member of the project. */
const val MEMBER_PRESENT: Long = 1L

/** The expected value of a member proposal: the assignee is not a member of the project. */
const val MEMBER_ABSENT: Long = 0L

/** The state of a proposal row (V56). PROPOSED is the only state that can still be confirmed or dismissed. */
enum class ChatActionState { PROPOSED, EXECUTED, DISMISSED, EXPIRED, FAILED }

/**
 * The fixed result codes of a resolved action. A refusal from the repository is stored under its own enum name (the `OrderConflict` names),
 * so the client maps those too. Nothing here is free text.
 */
object ChatResultCode {
    const val OK = "OK"
    const val OPERATOR_DISMISSED = "OPERATOR_DISMISSED"
    const val VERSION_MOVED = "VERSION_MOVED"
    const val NO_LONGER_ELIGIBLE = "NO_LONGER_ELIGIBLE"
    const val STALE_VERSION = "STALE_VERSION"
    const val ORDER_NOT_FOUND = "ORDER_NOT_FOUND"
    const val TASK_NOT_FOUND = "TASK_NOT_FOUND"
    const val TASK_NOT_REPLANNABLE = "TASK_NOT_REPLANNABLE"
    const val TASK_STOP_REFUSED = "TASK_STOP_REFUSED"
    const val UNKNOWN_ACTION = "UNKNOWN_ACTION"
    const val TASK_NOT_APPROVABLE = "TASK_NOT_APPROVABLE"
    const val TASK_NOT_REJECTABLE = "TASK_NOT_REJECTABLE"

    /** The other approval proposal of the same Task was resolved first (executed, failed or expired): this alternative is expired. */
    const val SIBLING_RESOLVED = "SIBLING_RESOLVED"

    // The member proposals (ADR 0023 追補 5): the members route's outcomes, as fixed codes.
    const val PROJECT_NOT_FOUND = "PROJECT_NOT_FOUND"
    const val ASSIGNEE_NOT_FOUND = "ASSIGNEE_NOT_FOUND"
    const val NOT_MEMBER = "NOT_MEMBER"
    const val ALREADY_MEMBER = "ALREADY_MEMBER"
    const val LAST_ADMIN = "LAST_ADMIN"
    const val INVALID_ROLE = "INVALID_ROLE"
}

/**
 * The facts of one root order that the proposer reads. [expired] is true when the order's lifetime has ended. [cycleStuck] is
 * [isCycleStuck] of its cycle in progress (false when there is none).
 */
data class ChatOrderFacts(
    val orderId: String,
    val state: String,
    val version: Long,
    val currentGoalId: String?,
    val cyclesStarted: Int,
    val maxCycles: Int,
    val expired: Boolean,
    val cycleStuck: Boolean,
    /** The cycle's root Task (the order's `current_goal_id`), or null when there is no cycle in progress. Read by TASK_REPLAN only. */
    val cycleTask: ChatCycleTaskFact? = null,
    /** The child Tasks of the cycle's root that wait for approval (read by the approval rules only). Empty without a cycle in progress. */
    val approvals: List<ChatApprovalFact> = emptyList(),
)

/** A child Task of a cycle as the approval rule reads it: its ID, version, state, and whether it is a plan root (revision > 0). */
data class ChatApprovalFact(val taskId: String, val version: Long, val state: String, val isPlanRoot: Boolean)

/**
 * True when an operator may approve or reject the Task from the chat: PENDING_APPROVAL and not a plan root. The same condition as the goal
 * page's buttons (kivra-compose-ui DetailScreens: PENDING_APPROVAL and revision 0). The operation refuses a plan root anyway.
 */
fun isApprovable(task: ChatApprovalFact): Boolean = task.state == "PENDING_APPROVAL" && !task.isPlanRoot

/** The cycle's root Task as the replan rule reads it: its ID, version, state and state reason (the stored enum name, or null). */
data class ChatCycleTaskFact(val taskId: String, val version: Long, val state: String, val stateReason: String?)

/**
 * The reasons a BLOCKED Task may be proposed for a replan: the planning-stage blocks ([PLAN_BLOCK_REASONS], stored as enum names). The same set
 * as the goal page's `canReplanGoal` (kivra-compose-ui GoalReplanRules.kt). The goal route itself accepts any BLOCKED Task; the chat does not.
 */
val REPLANNABLE_BLOCK_REASONS: Set<String> = PLAN_BLOCK_REASONS.map { it.name }.toSet()

/** True when the cycle's root Task may be proposed for a replan: BLOCKED, for a planning-stage reason. */
fun isReplannable(task: ChatCycleTaskFact): Boolean =
    task.state == "BLOCKED" && task.stateReason != null && task.stateReason in REPLANNABLE_BLOCK_REASONS

/**
 * One proposal the rules make for the current facts: the code, its target (an order, or a Task for [ChatTargetKind.TASK]) and that row's
 * version at the time (the order's or the Task's `version`).
 */
data class ChatActionProposal(val code: ChatActionCode, val targetId: String, val expectedVersion: Long)

/**
 * The proposals for the root orders of a project (ADR 0023 section 2):
 *
 * - ORDER_START_CYCLE: ACTIVE, not expired, no cycle in progress, under `max_cycles`. The failure count is NOT a condition: it stops the
 *   automatic start only, and the operator's manual start (the REST route) stays allowed after failures.
 * - ORDER_ABANDON_CYCLE: ACTIVE, a cycle in progress, and [ChatOrderFacts.cycleStuck]. A PAUSED order gets no abandon proposal, the same as
 *   the UI's own rule for the button.
 */
fun proposeChatActions(facts: List<ChatOrderFacts>): List<ChatActionProposal> = facts.flatMap { order ->
    val active = order.state == ACTIVE_STATE
    buildList {
        if (active && !order.expired && order.currentGoalId == null && order.cyclesStarted < order.maxCycles) {
            add(ChatActionProposal(ChatActionCode.ORDER_START_CYCLE, order.orderId, order.version))
        }
        if (active && order.currentGoalId != null && order.cycleStuck) {
            add(ChatActionProposal(ChatActionCode.ORDER_ABANDON_CYCLE, order.orderId, order.version))
        }
        val task = order.cycleTask
        if (active && task != null && isReplannable(task)) {
            add(ChatActionProposal(ChatActionCode.TASK_REPLAN, task.taskId, task.version))
        }
        // Two alternatives per waiting child: approve, or reject. Resolving one expires the other (see the repository).
        if (active && order.currentGoalId != null) {
            for (child in order.approvals.filter(::isApprovable)) {
                add(ChatActionProposal(ChatActionCode.TASK_APPROVE, child.taskId, child.version))
                add(ChatActionProposal(ChatActionCode.TASK_REJECT, child.taskId, child.version))
            }
        }
    }
}

/**
 * The fixed text that says why a Task waits for approval, from its state reason (the stored enum name, or null). The Task's title is shown
 * beside it as AI-written text; this text is the server's own.
 */
fun approvalReasonText(stateReason: String?): String = when (stateReason) {
    null -> "この Task は実行前に承認が必要です。"
    "AUTO_SCOPE_EXCEEDED" -> "自動実行の範囲を超える変更があったため、承認が必要です。"
    else -> "承認待ちの Task です。"
}

/** A Task of a cycle, as the stuck rule reads it: its state and the IDs it depends on. */
data class ChatTaskFact(val taskId: String, val state: String, val dependencies: List<String>)

/** The Task states that end a Task (no further progress by itself). */
val ENDED_TASK_STATES: Set<String> = setOf("COMPLETED", "DONE", "FAILED", "CANCELLED", "SKIPPED", "STOPPED")

/** The dependency states that can never be satisfied: a QUEUED Task waiting on one of these is blocked for good. */
val BLOCKING_DEPENDENCY_STATES: Set<String> = setOf("FAILED", "STOPPED")

/**
 * The conservative stuck rule of a cycle in progress (ADR 0023 section 2, stage 1). A cycle is stuck only when all of these hold:
 *
 * - its root Task has not ended by itself (an ended root is closed by the evaluator, not by an operator);
 * - it has open child Tasks (children not in [ENDED_TASK_STATES]);
 * - every open child is QUEUED; and
 * - every open child depends on at least one Task in [BLOCKING_DEPENDENCY_STATES].
 *
 * Anything else (a RUNNING, BLOCKED, PAUSED or PLANNING child, a child without a failed dependency, no open child) is not stuck. The rule can
 * miss a stuck cycle; it must not abandon a working one. [stateOf] returns the state of a Task ID, or null when unknown (an unknown dependency
 * does not count as blocking).
 */
fun isCycleStuck(rootEnded: Boolean, children: List<ChatTaskFact>, stateOf: (String) -> String?): Boolean {
    if (rootEnded) return false
    val open = children.filter { it.state !in ENDED_TASK_STATES }
    if (open.isEmpty()) return false
    return open.all { child ->
        child.state == "QUEUED" && child.dependencies.any { dep -> stateOf(dep) in BLOCKING_DEPENDENCY_STATES }
    }
}

private const val ACTIVE_STATE = "ACTIVE"
